% TOOLBOX: Signal Processing Toolbox.
% The course code below creates both filters. After the app opens, import
% designedFIR and designedIIR as Filter Objects, then compare Group Delay
% and Phase. Detailed observed UI steps are in lesson07_filter_analyzer_gui.md.
% This standalone setup has not been independently executed.

%% Provided course signal setup
[flute,fs]=audioread("NoisyFlute.wav");
flute=flute(1:3*fs);
t=((0:numel(flute)-1)/fs)';
yin=chirp(t,2200,t(end),2500)*0.0005;
marked=flute+yin;

%% Provided FIR design
designedFIR=designfilt('bandpassfir', ...
    'StopbandFrequency1',2100, ...
    'PassbandFrequency1',2200, ...
    'PassbandFrequency2',2500, ...
    'StopbandFrequency2',2600, ...
    'StopbandAttenuation1',80, ...
    'PassbandRipple',1, ...
    'StopbandAttenuation2',60, ...
    'SampleRate',fs);

%% Provided IIR design (this lesson did not supply ScaleSOS)
designedIIR=designfilt('bandpassiir', ...
    'StopbandFrequency1',2100, ...
    'PassbandFrequency1',2200, ...
    'PassbandFrequency2',2500, ...
    'StopbandFrequency2',2600, ...
    'StopbandAttenuation1',60, ...
    'PassbandRipple',1, ...
    'StopbandAttenuation2',60, ...
    'SampleRate',fs);

%% Launch the app for the manual import/comparison workflow
filterAnalyzer;
