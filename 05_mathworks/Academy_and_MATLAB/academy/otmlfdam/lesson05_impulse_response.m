%% Course signal setup
[flute,fs]=audioread("NoisyFlute.wav");
flute=flute(1:3*fs);
t=((0:numel(flute)-1)/fs)';
yin=chirp(t,2200,t(end),2500)*0.0005;
marked=flute+yin;

%% Task 1: FIR design and impulse response
designedFIR=designfilt('bandpassfir', ...
    'StopbandFrequency1',2100, ...
    'PassbandFrequency1',2200, ...
    'PassbandFrequency2',2500, ...
    'StopbandFrequency2',2600, ...
    'StopbandAttenuation1',80, ...
    'PassbandRipple',1, ...
    'StopbandAttenuation2',60, ...
    'SampleRate',16000);
figure('Name','FIR frequency response');
freqz(designedFIR,[],fs);
figure('Name','FIR impulse response');
impz(designedFIR,[],fs);

%% Task 2: IIR design and impulse response
designedIIR=designfilt('bandpassiir', ...
    'StopbandFrequency1',2100, ...
    'PassbandFrequency1',2200, ...
    'PassbandFrequency2',2500, ...
    'StopbandFrequency2',2600, ...
    'StopbandAttenuation1',60, ...
    'PassbandRipple',1, ...
    'StopbandAttenuation2',60, ...
    'SampleRate',16000, ...
    'ScaleSOS',true);
figure('Name','IIR impulse response');
impz(designedIIR,[],fs);

